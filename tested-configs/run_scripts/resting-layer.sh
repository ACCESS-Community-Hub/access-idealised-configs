#!/bin/bash
#==============================================================================
# Run the MOM6-examples test case "ocean_only/resting/layer" on NCI Gadi
# with the prebuilt MOM6 ocean-only ("solo") executable from ACCESS-OM3.
#
# Usage (from a Gadi *login node*, NOT from inside an ARE/JupyterLab container):
#     PROJECT=<your NCI project> bash resting-layer.sh
#
# What it does:
#   1. clones NOAA-GFDL/MOM6-examples (configs only) at the commit we tested;
#   2. links the shared MOM6-examples input data (only some examples need it);
#   3. writes a payu config.yaml into the example directory;
#   4. submits the run with `payu run` (output lands in $LAB/archive/resting-layer).
#
# This file was generated by tested-configs/regenerate_all.sh in
# github.com/ACCESS-Community-Hub/mom6-idealised-configs (written with Claude Code).
#==============================================================================
set -euo pipefail

# ---- Settings you may want to change ----------------------------------------
PROJECT=${PROJECT:?"Please set PROJECT to your NCI project, e.g. PROJECT=tm70"}
EXAMPLES_DIR=${EXAMPLES_DIR:-/g/data/$PROJECT/$USER/MOM6-examples}  # where MOM6-examples is cloned
LAB=${LAB:-/scratch/$PROJECT/$USER/mom6-examples}                   # payu "laboratory" (work + archive)

# ---- Pinned versions (exactly what was tested) -------------------------------
MOM6_EXAMPLES_COMMIT=c1730b8efe16cf7f12fc8db588115cae50f3e802   # NOAA-GFDL/MOM6-examples, branch dev/gfdl
ACCESS_OM3_MODULE=access-om3/2026.05.004          # provides the `mom6-solo` executable
PAYU_MODULE=payu/1.3.6_1
DATASETS=/g/data/ol01/access-iom3-configs/mom6exampledata/backup   # unpacked copy of GFDL's MOM6-examples input data

# ---- This example ------------------------------------------------------------
EXAMPLE=ocean_only/resting/layer        # directory inside MOM6-examples
EXPT_NAME=resting-layer    # payu experiment name (must be unique in $LAB)
NCPUS=2            # = NIPROC x NJPROC used by GFDL for this example
WALLTIME=00:30:00

# ---- 1. Get the MOM6-examples configurations ---------------------------------
# Submodules (MOM6/FMS source code, ...) are NOT needed: the executable is prebuilt.
if [ ! -d "$EXAMPLES_DIR/.git" ]; then
    git clone https://github.com/NOAA-GFDL/MOM6-examples.git "$EXAMPLES_DIR"
fi
cd "$EXAMPLES_DIR"
[ "$(git rev-parse HEAD)" = "$MOM6_EXAMPLES_COMMIT" ] \
    || git -c advice.detachedHead=false checkout "$MOM6_EXAMPLES_COMMIT"

# ---- 2. Link the input data --------------------------------------------------
# Each example's INPUT/ contains `.datasets -> ../../../.datasets`, so one link
# at the top of the clone is enough.
[ -e .datasets ] || ln -s "$DATASETS" .datasets

# ---- 3. Write a payu configuration into the example directory ---------------
cd "$EXAMPLES_DIR/$EXAMPLE"
# Examples that ship an INPUT/ directory (grids, forcing, ...) hand it to payu.
INPUT_LINE=""
[ -d INPUT ] && INPUT_LINE="input: $PWD/INPUT"
# Some examples switch restart files off (RESTART_CONTROL = -1), but payu still
# expects a work/RESTART directory when it archives: create an empty one after the run.
USERSCRIPT_LINES=""
if grep -q -E "^RESTART_CONTROL *= *-1" MOM_input MOM_override; then
    USERSCRIPT_LINES="userscripts:             # this example writes no restart files
  run: mkdir -p $LAB/work/$EXPT_NAME/RESTART"
fi

cat > config.yaml <<EOF
# payu configuration for MOM6-examples/$EXAMPLE (written by $(basename "$0"))
project: $PROJECT
queue: normalsr          # mom6-solo is compiled for Sapphire Rapids nodes
ncpus: $NCPUS
walltime: $WALLTIME
jobname: $EXPT_NAME
experiment: $EXPT_NAME
laboratory: $LAB

model: mom6
exe: mom6-solo           # found on PATH once the module below is loaded
$INPUT_LINE
$USERSCRIPT_LINES
modules:
  use:
    - /g/data/vk83/modules
  load:
    - $ACCESS_OM3_MODULE

storage:                 # vk83: executable, ol01: input data
  gdata:
    - vk83
    - ol01

collate: false           # mom6 writes un-split netCDF files when IO_LAYOUT = 1,1
runlog: false            # don't commit run logs into the MOM6-examples clone
metadata:
  enable: false
EOF

# ---- 4. Run it ----------------------------------------------------------------
module use /g/data/vk83/modules
module load "$PAYU_MODULE"
payu sweep > /dev/null 2>&1 || true   # tidy any previous failed attempt
payu run
echo "Submitted. Check with: qstat -u \$USER ; output: $LAB/archive/$EXPT_NAME/output000"
